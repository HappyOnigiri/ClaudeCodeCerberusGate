// Ship the pinned engine's input references without a runtime dependency on its types.
import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { parse, walk } from "./quality/source.mjs";

const source = "types/claude-code-tools/index.d.ts";
const target = "plugins/cerberus-gate/hooks/tool-inputs.ts";
const text = await readFile(source, "utf8");
const { program, comments } = parse(source, text);
const inputs = {};
walk(program, (node) => {
  if (node.type !== "TSInterfaceDeclaration" || node.id.name !== "BuiltinToolInputs") return;
  for (const property of node.body.body) {
    const type = property.typeAnnotation.typeAnnotation;
    let reference = text.slice(type.start, type.end);
    for (const comment of comments
      .filter((c) => c.start >= type.start && c.end <= type.end)
      .reverse())
      reference =
        reference.slice(0, comment.start - type.start) + reference.slice(comment.end - type.start);
    inputs[property.key.name ?? property.key.value] = reference
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean)
      .join("\n");
  }
});
if (!Object.keys(inputs).length) throw new Error("No built-in input references found");
const generated = execFileSync("node_modules/.bin/oxfmt", ["--stdin-filepath", target], {
  input:
    "// Code generated by scripts/review-inputs.mjs. DO NOT EDIT.\n" +
    "export const BUILTIN_INPUTS: Readonly<Record<string, string>> = " +
    JSON.stringify(inputs, null, 2) +
    ";\n",
  encoding: "utf8",
});
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== generated)
    throw new Error("Stale tool input references; run node scripts/review-inputs.mjs");
} else await writeFile(target, generated);
